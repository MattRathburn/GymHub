using GymHub.BuildingBlocks.Persistence;
using GymHub.Modules.Programs.Domain;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace GymHub.Modules.Programs.Data;

public sealed class ProgramsDbContext(DbContextOptions<ProgramsDbContext> options) : ModuleDbContext(options)
{
    public const string SchemaName = "programs";

    public override string Schema => SchemaName;

    public DbSet<TrainingProgram> Programs => Set<TrainingProgram>();

    /// <summary>Loads a program with its whole content tree, ready for editing.</summary>
    public Task<TrainingProgram?> LoadProgramAsync(Guid id, CancellationToken cancellationToken) =>
        Programs
            .Include(p => p.Prices)
            .Include(p => p.Media)
            .Include(p => p.Weeks).ThenInclude(w => w.Days).ThenInclude(d => d.Workouts).ThenInclude(w => w.Exercises)
            .AsSplitQuery()
            .SingleOrDefaultAsync(p => p.Id == id, cancellationToken);

    public override async Task<int> SaveChangesAsync(CancellationToken cancellationToken = default)
    {
        var programs = ChangeTracker.Entries<TrainingProgram>().Select(e => e.Entity).ToList();

        foreach (var program in programs)
        {
            foreach (var @event in program.Events)
            {
                AddIntegrationEvent(@event);
            }

            program.ClearEvents();
        }

        return await base.SaveChangesAsync(cancellationToken);
    }

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        base.OnModelCreating(modelBuilder);

        modelBuilder.Entity<TrainingProgram>(ConfigureProgram);
        modelBuilder.Entity<PriceVersion>(ConfigurePrice);
        modelBuilder.Entity<ProgramWeek>(ConfigureWeek);
        modelBuilder.Entity<ProgramDay>(ConfigureDay);
        modelBuilder.Entity<Workout>(ConfigureWorkout);
        modelBuilder.Entity<Exercise>(ConfigureExercise);
        modelBuilder.Entity<MediaAttachment>(ConfigureMedia);
    }

    // Child ids are generated by the domain, so EF must not treat a set key as "already saved".

    private static void ConfigureProgram(EntityTypeBuilder<TrainingProgram> program)
    {
        program.ToTable("programs");
        program.HasKey(p => p.Id);
        program.Property(p => p.Id).ValueGeneratedNever();
        program.Property(p => p.TrainerId).HasMaxLength(100);
        program.Property(p => p.Title).HasMaxLength(200);
        program.Property(p => p.Summary).HasMaxLength(500);
        program.Property(p => p.CoverObjectKey).HasMaxLength(300);
        program.Property(p => p.Kind).HasConversion<string>().HasMaxLength(20);
        program.Property(p => p.Status).HasConversion<string>().HasMaxLength(20);
        program.HasIndex(p => p.TrainerId);
        program.HasIndex(p => p.Status);
        program.Ignore(p => p.CurrentPrice);
        program.Ignore(p => p.MediaKeyPrefix);

        program.HasMany(p => p.Prices).WithOne().HasForeignKey("ProgramId").OnDelete(DeleteBehavior.Cascade);
        program.HasMany(p => p.Weeks).WithOne().HasForeignKey("ProgramId").OnDelete(DeleteBehavior.Cascade);
        program.HasMany(p => p.Media).WithOne().HasForeignKey("ProgramId").OnDelete(DeleteBehavior.Cascade);
    }

    private static void ConfigurePrice(EntityTypeBuilder<PriceVersion> price)
    {
        price.ToTable("price_versions");
        price.HasKey("ProgramId", nameof(PriceVersion.Version));
        price.Property(v => v.Version).ValueGeneratedNever();
        price.ComplexProperty(v => v.Price, p =>
        {
            p.Property(x => x.Model).HasConversion<string>().HasMaxLength(20).HasColumnName("Model");
            p.Property(x => x.AmountMinor).HasColumnName("AmountMinor");
            p.Property(x => x.Currency).HasMaxLength(3).HasColumnName("Currency");
            p.Property(x => x.Interval).HasConversion<string>().HasMaxLength(20).HasColumnName("Interval");
            p.Property(x => x.TrialDays).HasColumnName("TrialDays");
        });
    }

    private static void ConfigureWeek(EntityTypeBuilder<ProgramWeek> week)
    {
        week.ToTable("weeks");
        week.HasKey(w => w.Id);
        week.Property(w => w.Id).ValueGeneratedNever();
        week.Property(w => w.Title).HasMaxLength(200);
        week.HasIndex(w => new { w.ReleasesOn, w.ReleaseAnnouncedAt });
        week.HasMany(w => w.Days).WithOne().HasForeignKey("WeekId").OnDelete(DeleteBehavior.Cascade);
    }

    private static void ConfigureDay(EntityTypeBuilder<ProgramDay> day)
    {
        day.ToTable("days");
        day.HasKey(d => d.Id);
        day.Property(d => d.Id).ValueGeneratedNever();
        day.Property(d => d.Title).HasMaxLength(200);
        day.HasIndex("WeekId", nameof(ProgramDay.Number)).IsUnique();
        day.HasMany(d => d.Workouts).WithOne().HasForeignKey("DayId").OnDelete(DeleteBehavior.Cascade);
    }

    private static void ConfigureWorkout(EntityTypeBuilder<Workout> workout)
    {
        workout.ToTable("workouts");
        workout.HasKey(w => w.Id);
        workout.Property(w => w.Id).ValueGeneratedNever();
        workout.Property(w => w.Title).HasMaxLength(200);
        workout.HasMany(w => w.Exercises).WithOne().HasForeignKey("WorkoutId").OnDelete(DeleteBehavior.Cascade);
    }

    private static void ConfigureExercise(EntityTypeBuilder<Exercise> exercise)
    {
        exercise.ToTable("exercises");
        exercise.HasKey(e => e.Id);
        exercise.Property(e => e.Id).ValueGeneratedNever();
        exercise.Property(e => e.Name).HasMaxLength(200);
        exercise.OwnsMany(e => e.Sets, sets => sets.ToJson());
    }

    private static void ConfigureMedia(EntityTypeBuilder<MediaAttachment> media)
    {
        media.ToTable("media");
        media.HasKey(m => m.Id);
        media.Property(m => m.Id).ValueGeneratedNever();
        media.Property(m => m.TargetKind).HasConversion<string>().HasMaxLength(20);
        media.Property(m => m.Kind).HasConversion<string>().HasMaxLength(20);
        media.Property(m => m.ObjectKey).HasMaxLength(300);
        media.Property(m => m.ContentType).HasMaxLength(100);
        media.Property(m => m.Caption).HasMaxLength(300);
        media.HasIndex(m => new { m.TargetKind, m.TargetId });
    }
}
